// Embed the GMharness source tree into `src/assets.gen.ts`.
//
//     bun run script/generate-assets.ts
//
// The `gm` binary is compiled and shipped on its own, so every file it needs at
// runtime — agents, commands, skills, config templates, scripts, utilities — is
// baked into the binary as text. Files another worker has not written yet are
// skipped with a warning instead of failing the build.

import { createHash } from "node:crypto"
import { existsSync, mkdirSync, readFileSync, readdirSync, statSync, writeFileSync } from "node:fs"
import { dirname, join, relative, resolve, sep } from "node:path"

const packageDir = resolve(import.meta.dir, "..")
const root = process.env.GMHARNESS_ROOT ? resolve(process.env.GMHARNESS_ROOT) : resolve(packageDir, "../../..")
const output = join(packageDir, "src", "assets.gen.ts")

/** Single files, path relative to the repo root. */
const files = [
  "AGENTS.md",
  "config/opencode.jsonc",
  "config/.env.example",
  "scripts/gm_sync.py",
  "scripts/doctor.sh",
  "scripts/opencode-config-guard",
  "systemd/gmharness-sync.service",
  "systemd/gmharness-sync.timer",
]

/** Directories copied recursively; only text files are embedded. */
const trees = ["agents", "commands", "context", "skills"]

/** `bin/` is copied by prefix: `bin/aiops` plus every `bin/ws-*`. */
const binDir = "bin"

const assets = new Map<string, string>()
const warnings: string[] = []

for (const path of files) addFile(path)

for (const tree of trees) {
  const absolute = join(root, tree)
  if (!existsSync(absolute)) {
    warnings.push(`${tree}/ (missing)`)
    continue
  }
  for (const file of walk(absolute)) addFile(relative(root, file).split(sep).join("/"))
}

if (existsSync(join(root, binDir))) {
  const entries = readdirSync(join(root, binDir))
  const ws = entries.filter((entry) => entry.startsWith("ws-"))
  if (!ws.length) warnings.push(`${binDir}/ws-* (none found)`)
  for (const entry of entries) {
    if (entry !== "aiops" && !entry.startsWith("ws-")) continue
    addFile(`${binDir}/${entry}`)
  }
} else {
  warnings.push(`${binDir}/ (missing)`)
}

const names = [...assets.keys()].sort()
const hash = createHash("sha256")
for (const name of names) hash.update(name).update("\0").update(assets.get(name) ?? "").update("\0")
const digest = hash.digest("hex")
const version = process.env.GMHARNESS_ASSET_VERSION || digest.slice(0, 12)

mkdirSync(dirname(output), { recursive: true })
writeFileSync(output, render(names, digest, version), "utf8")

if (warnings.length) {
  console.warn(`skipped ${warnings.length} asset source(s):`)
  for (const warning of warnings) console.warn(`  ! ${warning}`)
}
console.log(`embedded ${names.length} assets from ${root}`)
console.log(`  version ${version} (sha256 ${digest.slice(0, 12)}…)`)
console.log(`  wrote ${relative(process.cwd(), output) || output}`)

function addFile(path: string) {
  const absolute = join(root, path)
  if (!existsSync(absolute)) {
    warnings.push(`${path} (missing)`)
    return
  }
  const stats = statSync(absolute)
  if (!stats.isFile()) return
  const buffer = readFileSync(absolute)
  if (isBinary(buffer)) {
    warnings.push(`${path} (binary, skipped)`)
    return
  }
  assets.set(path, buffer.toString("utf8"))
}

/** Text check: a NUL byte in the first 8 KiB means "do not embed". */
function isBinary(buffer: Buffer) {
  const sample = buffer.subarray(0, 8192)
  return sample.includes(0)
}

function walk(dir: string) {
  const result: string[] = []
  for (const entry of readdirSync(dir, { withFileTypes: true })) {
    if (entry.name === "__pycache__" || entry.name === ".git" || entry.name.startsWith(".")) continue
    const path = join(dir, entry.name)
    if (entry.isDirectory()) result.push(...walk(path))
    else if (entry.isFile()) result.push(path)
  }
  return result
}

function render(names: string[], digest: string, version: string) {
  const entries = names.map((name) => `  ${JSON.stringify(name)}: ${JSON.stringify(assets.get(name) ?? "")},`)
  return [
    "// Generated by script/generate-assets.ts — do not edit by hand.",
    "// Run `bun run assets` in packages/gmharness after changing any source file.",
    "",
    "export const ASSET_VERSION = " + JSON.stringify(version),
    "export const ASSET_HASH = " + JSON.stringify(digest),
    "",
    "export const ASSETS: Record<string, string> = {",
    ...entries,
    "}",
    "",
  ].join("\n")
}
